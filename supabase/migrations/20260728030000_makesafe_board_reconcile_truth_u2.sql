-- SES Reporting U2: atomic board reconciliation plus visible Captain actions.
--
-- SCHEMA/RPC ONLY. This migration performs no data backfill, no authority flip,
-- and no operational status/substatus mutation. The privileged edge action is
-- dark by default and is not invoked by this PR.

CREATE TABLE IF NOT EXISTS public.makesafe_state_identity_revisions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id uuid NOT NULL,
  job_id uuid NOT NULL REFERENCES public.jobs(id) ON DELETE RESTRICT,
  authority_kind text NOT NULL CHECK (authority_kind IN (
    'effective_intake_case', 'legacy_job_record', 'unresolved_authority'
  )),
  effective_case_id uuid
    REFERENCES public.makesafe_intake_cases(id) ON DELETE RESTRICT,
  source_instruction_id text NOT NULL
    CHECK (length(btrim(source_instruction_id)) > 0),
  source_version bigint NOT NULL CHECK (source_version > 0),
  source_content_hash text NOT NULL
    CHECK (source_content_hash ~ '^sha256:[0-9a-f]{64}$'),
  lineage_id text NOT NULL CHECK (length(btrim(lineage_id)) > 0),
  lineage_version bigint NOT NULL CHECK (lineage_version > 0),
  lineage_correction_hash text NOT NULL
    CHECK (lineage_correction_hash ~ '^sha256:[0-9a-f]{64}$'),
  lineage_supersession_hash text NOT NULL
    CHECK (lineage_supersession_hash ~ '^sha256:[0-9a-f]{64}$'),
  intake_state text,
  family_state text NOT NULL CHECK (family_state IN ('resolved', 'unresolved')),
  family_rule_key text,
  blocker_code text,
  recovery_instruction text,
  evidence_refs jsonb NOT NULL
    CHECK (
      jsonb_typeof(evidence_refs) = 'array'
      AND jsonb_array_length(evidence_refs) > 0
    ),
  revision_hash text NOT NULL
    CHECK (revision_hash ~ '^sha256:[0-9a-f]{64}$'),
  created_by text NOT NULL CHECK (length(btrim(created_by)) > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT makesafe_state_identity_case_shape CHECK (
    (authority_kind = 'effective_intake_case' AND effective_case_id IS NOT NULL)
    OR
    (authority_kind <> 'effective_intake_case' AND effective_case_id IS NULL)
  ),
  CONSTRAINT makesafe_state_identity_family_shape CHECK (
    (family_state = 'resolved' AND family_rule_key IS NOT NULL)
    OR
    (
      family_state = 'unresolved'
      AND family_rule_key IS NULL
      AND length(btrim(COALESCE(recovery_instruction, ''))) > 0
    )
  ),
  UNIQUE (job_id, revision_hash)
);

CREATE INDEX IF NOT EXISTS idx_makesafe_state_identity_revisions_current
  ON public.makesafe_state_identity_revisions
  (job_id, created_at DESC, id DESC);

CREATE OR REPLACE VIEW public.makesafe_state_identity_current_v2
WITH (security_invoker = true)
AS
SELECT DISTINCT ON (job_id)
  id,
  org_id,
  job_id,
  authority_kind,
  effective_case_id,
  source_instruction_id,
  source_version,
  source_content_hash,
  lineage_id,
  lineage_version,
  lineage_correction_hash,
  lineage_supersession_hash,
  intake_state,
  family_state,
  family_rule_key,
  blocker_code,
  recovery_instruction,
  evidence_refs,
  revision_hash,
  created_by,
  created_at
FROM public.makesafe_state_identity_revisions
ORDER BY job_id, created_at DESC, id DESC;

