CREATE OR REPLACE FUNCTION public.apply_makesafe_board_reconciliation(
  p_run_key text,
  p_applied_by text,
  p_selection_hash text,
  p_rows jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_requested integer;
  v_distinct integer;
  v_trustworthy integer;
  v_captain_marked integer;
  v_transitions integer;
  v_attention integer;
  v_result jsonb;
  v_existing public.makesafe_board_reconciliation_runs%ROWTYPE;
BEGIN
  IF length(btrim(COALESCE(p_run_key, ''))) = 0
     OR length(btrim(COALESCE(p_applied_by, ''))) = 0
     OR COALESCE(p_selection_hash, '') !~
       '^sha256:[0-9a-f]{64}$' THEN
    RAISE EXCEPTION
      'run key, attribution, and sha256 selection hash are required';
  END IF;
  IF jsonb_typeof(p_rows) <> 'array' THEN
    RAISE EXCEPTION 'p_rows must be a JSON array';
  END IF;

  SELECT * INTO v_existing
  FROM public.makesafe_board_reconciliation_runs
  WHERE run_key = p_run_key;
  IF FOUND THEN
    IF v_existing.selection_hash IS DISTINCT FROM p_selection_hash THEN
      RAISE EXCEPTION 'run key already belongs to a different selection';
    END IF;
    RETURN v_existing.result_json ||
      jsonb_build_object('idempotent_replay', true);
  END IF;

  v_requested := jsonb_array_length(p_rows);
  IF v_requested < 1 THEN
    RAISE EXCEPTION 'p_rows must contain at least one card';
  END IF;

  WITH incoming AS (
    SELECT *
    FROM jsonb_to_recordset(p_rows) AS x(
      job_id uuid,
      job_number text,
      outcome text,
      source_status text,
      before_status text,
      after_status text,
      computed_at timestamptz,
      computed_reasons jsonb,
      attendance_cycle_id uuid,
      attention_state text,
      attention_code text,
      attention_message text,
      attention_since timestamptz,
      attention_evidence_refs jsonb
    )
  )
  SELECT
    count(DISTINCT i.job_id),
    count(*) FILTER (WHERE i.outcome = 'trustworthy'),
    count(*) FILTER (WHERE i.outcome = 'captain_marked'),
    count(*) FILTER (WHERE i.after_status IS NOT NULL),
    count(*) FILTER (WHERE i.attention_state IS NOT NULL)
  INTO
    v_distinct,
    v_trustworthy,
    v_captain_marked,
    v_transitions,
    v_attention
  FROM incoming i
  JOIN public.jobs j
    ON j.id = i.job_id
   AND j.job_number = i.job_number
   AND j.type = 'makesafe'
  WHERE i.outcome IN ('trustworthy', 'captain_marked')
    AND (
      (i.outcome = 'captain_marked' AND i.attention_state = 'active')
      OR i.outcome = 'trustworthy'
    )
    AND (
      i.attention_state IS NULL
      OR (
        i.attention_state IN ('active', 'resolved')
        AND length(btrim(COALESCE(i.attention_code, ''))) > 0
        AND length(btrim(COALESCE(i.attention_message, ''))) > 0
        AND i.attention_since IS NOT NULL
        AND jsonb_typeof(
          COALESCE(i.attention_evidence_refs, '[]'::jsonb)
        ) = 'array'
      )
    );

  IF v_distinct <> v_requested
     OR v_trustworthy + v_captain_marked <> v_requested THEN
    RAISE EXCEPTION
      'reconciliation must partition every current make-safe exactly once';
  END IF;

  -- Verify every proposed display transition against the latest display overlay.
  IF EXISTS (
    WITH incoming AS (
      SELECT *
      FROM jsonb_to_recordset(p_rows) AS x(
        job_id uuid,
        job_number text,
        outcome text,
        source_status text,
        before_status text,
        after_status text,
        computed_at timestamptz,
        computed_reasons jsonb,
        attendance_cycle_id uuid,
        attention_state text,
        attention_code text,
        attention_message text,
        attention_since timestamptz,
        attention_evidence_refs jsonb
      )
    )
    SELECT 1
    FROM incoming i
    JOIN public.jobs j ON j.id = i.job_id
    LEFT JOIN LATERAL (
      SELECT a.after_status
      FROM public.makesafe_board_status_applications a
      WHERE a.job_id = i.job_id
        AND a.source_status = i.source_status
      ORDER BY a.applied_at DESC, a.id DESC
      LIMIT 1
    ) latest ON true
    WHERE i.after_status IS NOT NULL
      AND (
        i.outcome <> 'trustworthy'
        OR lower(COALESCE(j.status, '')) IN (
          'archived', 'complete', 'completed', 'closed',
          'cancelled', 'canceled', 'lost', 'deleted'
        )
        OR i.source_status NOT IN (
          'new', 'allocated', 'trade_report_in', 'report_ready'
        )
        OR i.before_status NOT IN (
          'new', 'allocated', 'trade_report_in', 'report_ready'
        )
        OR i.after_status NOT IN (
          'new', 'allocated', 'trade_report_in', 'report_ready',
          'completed', 'archive', 'cancelled'
        )
        OR i.before_status = i.after_status
        OR i.computed_at IS NULL
        OR jsonb_typeof(COALESCE(i.computed_reasons, '[]'::jsonb))
          <> 'array'
        OR jsonb_array_length(
          COALESCE(i.computed_reasons, '[]'::jsonb)
        ) = 0
        OR COALESCE(latest.after_status, i.source_status)
          IS DISTINCT FROM i.before_status
      )
  ) THEN
    RAISE EXCEPTION
      'one or more status corrections are stale, terminal, or lack evidence';
  END IF;

  WITH incoming AS (
    SELECT *
    FROM jsonb_to_recordset(p_rows) AS x(
      job_id uuid,
      job_number text,
      outcome text,
      source_status text,
      before_status text,
      after_status text,
      computed_at timestamptz,
      computed_reasons jsonb,
      attendance_cycle_id uuid,
      attention_state text,
      attention_code text,
      attention_message text,
      attention_since timestamptz,
      attention_evidence_refs jsonb
    )
  )
  INSERT INTO public.makesafe_board_status_applications (
    run_key,
    job_id,
    job_number,
    source_status,
    before_status,
    after_status,
    computed_at,
    computed_reasons,
    computed_missing,
    evidence_ref,
    applied_by
  )
  SELECT
    p_run_key,
    i.job_id,
    i.job_number,
    i.source_status,
    i.before_status,
    i.after_status,
    i.computed_at,
    i.computed_reasons,
    '[]'::jsonb,
    'makesafe-state.v2:' || p_selection_hash,
    p_applied_by
  FROM incoming i
  WHERE i.after_status IS NOT NULL;

  WITH incoming AS (
    SELECT *
    FROM jsonb_to_recordset(p_rows) AS x(
      job_id uuid,
      job_number text,
      outcome text,
      source_status text,
      before_status text,
      after_status text,
      computed_at timestamptz,
      computed_reasons jsonb,
      attendance_cycle_id uuid,
      attention_state text,
      attention_code text,
      attention_message text,
      attention_since timestamptz,
      attention_evidence_refs jsonb
    )
  )
  INSERT INTO public.makesafe_board_attention_marks (
    run_key,
    job_id,
    job_number,
    attendance_cycle_id,
    state,
    code,
    message,
    evidence_refs,
    computed_at,
    marked_by
  )
  SELECT
    p_run_key,
    i.job_id,
    i.job_number,
    i.attendance_cycle_id,
    i.attention_state,
    i.attention_code,
    i.attention_message,
    COALESCE(i.attention_evidence_refs, '[]'::jsonb),
    i.attention_since,
    p_applied_by
  FROM incoming i
  WHERE i.attention_state IS NOT NULL;

  v_result := jsonb_build_object(
    'ok', true,
    'run_key', p_run_key,
    'selection_hash', p_selection_hash,
    'requested', v_requested,
    'trustworthy', v_trustworthy,
    'captain_marked', v_captain_marked,
    'neither', 0,
    'transition_count', v_transitions,
    'attention_write_count', v_attention,
    'idempotent_replay', false
  );

  INSERT INTO public.makesafe_board_reconciliation_runs (
    run_key,
    selection_hash,
    requested_count,
    trustworthy_count,
    captain_marked_count,
    neither_count,
    transition_count,
    result_json,
    applied_by
  ) VALUES (
    p_run_key,
    p_selection_hash,
    v_requested,
    v_trustworthy,
    v_captain_marked,
    0,
    v_transitions,
    v_result,
    p_applied_by
  );

  RETURN v_result;
END;
$$;

