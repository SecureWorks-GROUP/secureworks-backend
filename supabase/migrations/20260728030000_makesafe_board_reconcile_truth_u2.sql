CREATE OR REPLACE FUNCTION public.makesafe_fact_hash_v1(
  p_kind text,
  p_payload jsonb
)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
SET search_path = public, extensions
AS $$
  SELECT 'sha256:' || encode(
    extensions.digest(
      convert_to(
        'SecureWorks:make-safe-fact:v1:' || p_kind || E'\n' ||
          public.makesafe_canonical_json_v1(p_payload),
        'UTF8'
      ),
      'sha256'
    ),
    'hex'
  );
$$;

CREATE OR REPLACE FUNCTION public.stamp_makesafe_fact_identity_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_is_makesafe boolean;
  v_payload jsonb;
  v_hash text;
  v_old_hash text;
  v_old_version bigint;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM public.jobs j
    WHERE j.id = NEW.job_id AND j.type = 'makesafe'
  ) INTO v_is_makesafe;
  IF NOT v_is_makesafe THEN
    RETURN NEW;
  END IF;

  -- Hash the row that actually exists in this database instead of naming a
  -- brittle table-specific column list. Identity fields and trigger-maintained
  -- timestamps are excluded so a no-op write keeps the same fact identity.
  v_payload := to_jsonb(NEW)
    - 'makesafe_fact_version'
    - 'makesafe_content_hash'
    - 'updated_at';

  v_hash := public.makesafe_fact_hash_v1(TG_TABLE_NAME, v_payload);
  IF TG_OP = 'INSERT' THEN
    NEW.makesafe_fact_version := 1;
    NEW.makesafe_content_hash := v_hash;
    RETURN NEW;
  END IF;

  v_old_hash := OLD.makesafe_content_hash;
  v_old_version := OLD.makesafe_fact_version;
  IF v_old_hash IS NULL OR v_old_version IS NULL THEN
    NEW.makesafe_fact_version := 1;
    NEW.makesafe_content_hash := v_hash;
  ELSIF v_hash IS DISTINCT FROM v_old_hash THEN
    NEW.makesafe_fact_version := v_old_version + 1;
    NEW.makesafe_content_hash := v_hash;
  ELSE
    NEW.makesafe_fact_version := v_old_version;
    NEW.makesafe_content_hash := v_old_hash;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.stamp_makesafe_intake_case_identity_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_source_payload jsonb;
  v_source_hash text;
  v_correction_hash text;
  v_supersession_hash text;
BEGIN
  -- The case row is the mutable source fact. Tracking columns and timestamps
  -- are excluded so a no-op maintenance write keeps the same source identity.
  v_source_payload := to_jsonb(NEW)
    - 'source_version'
    - 'source_content_hash'
    - 'lineage_version'
    - 'lineage_correction_hash'
    - 'lineage_supersession_hash'
    - 'updated_at'
    - 'observed_at'
    - 'last_decision_at';
  v_source_hash := public.makesafe_fact_hash_v1(
    'intake-source',
    v_source_payload
  );
  v_correction_hash := public.makesafe_fact_hash_v1(
    'lineage-corrections',
    jsonb_build_object(
      'case_id', NEW.id,
      'case_corrections', COALESCE((
        SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at, x.id)
        FROM public.makesafe_intake_case_authority_corrections x
        WHERE x.legacy_case_id = NEW.id OR x.effective_case_id = NEW.id
      ), '[]'::jsonb),
      'source_corrections', COALESCE((
        SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at, x.id)
        FROM public.makesafe_intake_source_authority_corrections x
        WHERE x.legacy_case_id = NEW.id OR x.effective_case_id = NEW.id
      ), '[]'::jsonb)
    )
  );
  v_supersession_hash := public.makesafe_fact_hash_v1(
    'lineage-supersessions',
    jsonb_build_object(
      'case_id', NEW.id,
      'supersessions', COALESCE((
        SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at, x.id)
        FROM
          public.makesafe_intake_source_authority_correction_supersessions x
        WHERE x.prior_authority_case_id = NEW.id
           OR x.effective_case_id = NEW.id
      ), '[]'::jsonb)
    )
  );

  IF TG_OP = 'INSERT' THEN
    NEW.source_version := 1;
    NEW.lineage_version := 1;
  ELSE
    NEW.source_version := CASE
      WHEN OLD.source_version IS NULL OR OLD.source_content_hash IS NULL THEN 1
      WHEN OLD.source_content_hash IS DISTINCT FROM v_source_hash
        THEN OLD.source_version + 1
      ELSE OLD.source_version
    END;
    NEW.lineage_version := CASE
      WHEN OLD.lineage_version IS NULL
        OR OLD.lineage_correction_hash IS NULL
        OR OLD.lineage_supersession_hash IS NULL THEN 1
      WHEN OLD.lineage_correction_hash IS DISTINCT FROM v_correction_hash
        OR OLD.lineage_supersession_hash IS DISTINCT FROM v_supersession_hash
        THEN OLD.lineage_version + 1
      ELSE OLD.lineage_version
    END;
  END IF;
  NEW.source_content_hash := v_source_hash;
  NEW.lineage_correction_hash := v_correction_hash;
  NEW.lineage_supersession_hash := v_supersession_hash;
  RETURN NEW;
END;
$$;

