AS $$
BEGIN
  IF TG_TABLE_NAME = 'makesafe_intake_case_authority_corrections' THEN
    UPDATE public.makesafe_intake_cases
    SET lineage_version = lineage_version
    WHERE id IN (NEW.legacy_case_id, NEW.effective_case_id);
