CREATE OR REPLACE FUNCTION public.finalize_makesafe_board_reconciliation(
  p_run_key text,
  p_applied_by text,
  p_selection_hash text,
  p_state_token_hash text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_chunk_count integer;
  v_staged_count integer;
  v_rows jsonb := '[]'::jsonb;
  v_chunk public.makesafe_board_reconciliation_staged_chunks%ROWTYPE;
  v_job_id uuid;
  v_result jsonb;
BEGIN
  IF COALESCE(p_selection_hash, '') !~ '^sha256:[0-9a-f]{64}$'
     OR COALESCE(p_state_token_hash, '') !~ '^sha256:[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'selection and state token hashes are required';
  END IF;
  SELECT max(chunk_count), count(*)::integer
    INTO v_chunk_count, v_staged_count
  FROM public.makesafe_board_reconciliation_staged_chunks
  WHERE run_key = p_run_key
    AND selection_hash = p_selection_hash
    AND state_token_hash = p_state_token_hash;
  IF v_chunk_count IS NULL THEN
    RAISE EXCEPTION 'reconciliation has no staged chunks';
  END IF;
  IF v_staged_count <> v_chunk_count
     OR (SELECT count(*) FROM public.makesafe_board_reconciliation_staged_chunks
      WHERE run_key = p_run_key) <> v_chunk_count
     OR EXISTS (
       SELECT 1
       FROM generate_series(1, v_chunk_count) n
       WHERE NOT EXISTS (
         SELECT 1 FROM public.makesafe_board_reconciliation_staged_chunks c
         WHERE c.run_key = p_run_key AND c.chunk_index = n
       )
     ) THEN
    RAISE EXCEPTION 'reconciliation staging is incomplete';
  END IF;
  FOR v_chunk IN
    SELECT * FROM public.makesafe_board_reconciliation_staged_chunks
    WHERE run_key = p_run_key ORDER BY chunk_index
  LOOP
    v_rows := v_rows || v_chunk.rows_json;
  END LOOP;
  FOR v_job_id IN
    SELECT DISTINCT job_id
    FROM jsonb_to_recordset(v_rows) AS x(job_id uuid)
    WHERE job_id IS NOT NULL
    ORDER BY job_id
  LOOP
    PERFORM 1 FROM public.jobs WHERE id = v_job_id FOR UPDATE;
    PERFORM 1 FROM public.makesafe_state_identity_revisions
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_attendance_cycles
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.job_assignments
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.job_service_reports
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.job_documents
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.job_media
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_portal_capture_revisions
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_intake_cases
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_status_holds
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_job_details
      WHERE job_id = v_job_id FOR SHARE;
    PERFORM 1 FROM public.makesafe_readiness_revisions
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_readiness_current
      WHERE job_id = v_job_id FOR SHARE;
    PERFORM 1 FROM public.makesafe_readiness_invalidations
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_cancellation_decisions
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_terminal_proofs
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_report_pack_cycles
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_report_packs
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_revision_approvals
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_board_status_applications
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1 FROM public.makesafe_board_attention_marks
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
    PERFORM 1
      FROM public.makesafe_family_rule_current c
      JOIN public.makesafe_state_identity_current_v2 i
        ON i.family_rule_key = c.family_code
       AND i.job_id = v_job_id
      JOIN public.makesafe_family_rule_revisions r
        ON r.id = c.revision_id
      FOR SHARE;
    PERFORM 1 FROM public.makesafe_docket_revisions
      WHERE job_id = v_job_id ORDER BY id FOR SHARE;
  END LOOP;
  PERFORM public.validate_makesafe_board_reconciliation_state_tokens(v_rows);
  v_result := public.apply_makesafe_board_reconciliation(
    p_run_key, p_applied_by, p_selection_hash, v_rows
  );
  DELETE FROM public.makesafe_board_reconciliation_staged_chunks
  WHERE run_key = p_run_key;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_makesafe_board_reconciliation_state_tokens(
  p_rows jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row record;
  v_token jsonb;
  v_expected text;
BEGIN
  FOR v_row IN
    SELECT * FROM jsonb_to_recordset(p_rows) AS x(
      job_id uuid,
      state_token text,
      state_facts jsonb
    )
  LOOP
    IF v_row.state_facts IS NULL
       OR jsonb_typeof(v_row.state_facts) <> 'object' THEN
      RAISE EXCEPTION 'reconciliation row % has no state facts', v_row.job_id;
    END IF;
    v_expected := 'sha256:' || encode(
      extensions.digest(
        convert_to(public.makesafe_canonical_json_v1(v_row.state_facts), 'UTF8'),
        'sha256'
      ),
      'hex'
    );
    IF v_row.state_token IS DISTINCT FROM v_expected THEN
      RAISE EXCEPTION 'reconciliation row % has a stale state token', v_row.job_id;
    END IF;
    IF (SELECT count(*) FROM public.makesafe_attendance_cycles WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_row.state_facts->'cycles', '[]'::jsonb))
      OR (SELECT count(*) FROM public.job_assignments WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_row.state_facts->'assignments', '[]'::jsonb))
      OR (SELECT count(*) FROM public.job_service_reports WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_row.state_facts->'service_reports', '[]'::jsonb))
      OR (SELECT count(*) FROM public.job_documents WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_row.state_facts->'documents', '[]'::jsonb))
      OR (SELECT count(*) FROM public.job_media WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_row.state_facts->'media', '[]'::jsonb))
      OR (SELECT count(*) FROM public.makesafe_portal_capture_revisions WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_row.state_facts->'portal_captures', '[]'::jsonb))
    THEN
      RAISE EXCEPTION 'reconciliation row % fact coverage changed', v_row.job_id;
    END IF;
    v_token := v_row.state_facts->'identity';
    IF v_token IS NOT NULL AND NOT EXISTS (
      SELECT 1
      FROM public.makesafe_state_identity_current_v2 i
      WHERE i.job_id = v_row.job_id
        AND i.id = (v_token->>'id')::uuid
        AND i.source_version IS NOT DISTINCT FROM (v_token->>'source_version')::bigint
        AND i.source_content_hash IS NOT DISTINCT FROM v_token->>'source_content_hash'
        AND i.lineage_id IS NOT DISTINCT FROM v_token->>'lineage_id'
        AND i.lineage_version IS NOT DISTINCT FROM (v_token->>'lineage_version')::bigint
        AND i.lineage_correction_hash IS NOT DISTINCT FROM v_token->>'lineage_correction_hash'
        AND i.lineage_supersession_hash IS NOT DISTINCT FROM v_token->>'lineage_supersession_hash'
        AND i.revision_hash IS NOT DISTINCT FROM v_token->>'revision_hash'
    ) THEN
      RAISE EXCEPTION 'reconciliation row % identity facts changed', v_row.job_id;
    END IF;
    v_token := v_row.state_facts->'readiness';
    IF v_token IS NOT NULL AND NOT EXISTS (
      SELECT 1
      FROM public.makesafe_readiness_current_v2 r
      WHERE r.job_id = v_row.job_id
        AND r.ready IS NOT DISTINCT FROM (v_token->>'ready')::boolean
        AND r.readiness_revision IS NOT DISTINCT FROM v_token->>'readiness_revision'
        AND r.dependency_generation IS NOT DISTINCT FROM (v_token->>'dependency_generation')::integer
        AND r.attendance_cycle_set_hash IS NOT DISTINCT FROM v_token->>'attendance_cycle_set_hash'
        AND r.invalidated_at IS NOT DISTINCT FROM (v_token->>'invalidated_at')::timestamptz
        AND r.invalidation_reason IS NOT DISTINCT FROM v_token->>'invalidation_reason'
        AND r.dependency_envelope IS NOT DISTINCT FROM v_token->'dependency_envelope'
    ) THEN
      RAISE EXCEPTION 'reconciliation row % readiness facts changed', v_row.job_id;
    END IF;
    IF EXISTS (
      SELECT 1
      FROM jsonb_array_elements(COALESCE(v_row.state_facts->'cycles', '[]'::jsonb)) e
      LEFT JOIN public.makesafe_attendance_cycles f
        ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
      WHERE f.id IS NULL
         OR f.cycle_number IS DISTINCT FROM (e->>'cycle_number')::integer
         OR f.opened_at IS DISTINCT FROM (e->>'opened_at')::timestamptz
         OR f.closed_at IS DISTINCT FROM (e->>'closed_at')::timestamptz
         OR f.makesafe_fact_version IS DISTINCT FROM (e->>'makesafe_fact_version')::bigint
         OR f.makesafe_content_hash IS DISTINCT FROM e->>'makesafe_content_hash'
    ) THEN RAISE EXCEPTION 'reconciliation row % cycle facts changed', v_row.job_id; END IF;
    IF EXISTS (
      SELECT 1
      FROM jsonb_array_elements(COALESCE(v_row.state_facts->'assignments', '[]'::jsonb)) e
      LEFT JOIN public.job_assignments f
        ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
      WHERE f.id IS NULL
         OR f.makesafe_fact_version IS DISTINCT FROM (e->>'makesafe_fact_version')::bigint
         OR f.makesafe_content_hash IS DISTINCT FROM e->>'makesafe_content_hash'
         OR f.attendance_cycle_id IS DISTINCT FROM NULLIF(e->>'attendance_cycle_id', '')::uuid
         OR f.cycle_attribution IS DISTINCT FROM e->>'cycle_attribution'
    ) THEN RAISE EXCEPTION 'reconciliation row % assignment facts changed', v_row.job_id; END IF;
    IF EXISTS (
      SELECT 1
      FROM jsonb_array_elements(COALESCE(v_row.state_facts->'service_reports', '[]'::jsonb)) e
      LEFT JOIN public.job_service_reports f
        ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
      WHERE f.id IS NULL
         OR f.makesafe_fact_version IS DISTINCT FROM (e->>'makesafe_fact_version')::bigint
         OR f.makesafe_content_hash IS DISTINCT FROM e->>'makesafe_content_hash'
         OR f.attendance_cycle_id IS DISTINCT FROM NULLIF(e->>'attendance_cycle_id', '')::uuid
         OR f.cycle_attribution IS DISTINCT FROM e->>'cycle_attribution'
    ) THEN RAISE EXCEPTION 'reconciliation row % report facts changed', v_row.job_id; END IF;
    IF EXISTS (
      SELECT 1
      FROM jsonb_array_elements(COALESCE(v_row.state_facts->'documents', '[]'::jsonb)) e
      LEFT JOIN public.job_documents f
        ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
      WHERE f.id IS NULL
         OR f.makesafe_fact_version IS DISTINCT FROM (e->>'makesafe_fact_version')::bigint
         OR f.makesafe_content_hash IS DISTINCT FROM e->>'makesafe_content_hash'
         OR f.attendance_cycle_id IS DISTINCT FROM NULLIF(e->>'attendance_cycle_id', '')::uuid
         OR f.cycle_attribution IS DISTINCT FROM e->>'cycle_attribution'
    ) THEN RAISE EXCEPTION 'reconciliation row % document facts changed', v_row.job_id; END IF;
    IF EXISTS (
      SELECT 1
      FROM jsonb_array_elements(COALESCE(v_row.state_facts->'media', '[]'::jsonb)) e
      LEFT JOIN public.job_media f
        ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
      WHERE f.id IS NULL
         OR f.makesafe_fact_version IS DISTINCT FROM (e->>'makesafe_fact_version')::bigint
         OR f.makesafe_content_hash IS DISTINCT FROM e->>'makesafe_content_hash'
         OR f.attendance_cycle_id IS DISTINCT FROM NULLIF(e->>'attendance_cycle_id', '')::uuid
         OR f.cycle_attribution IS DISTINCT FROM e->>'cycle_attribution'
    ) THEN RAISE EXCEPTION 'reconciliation row % media facts changed', v_row.job_id; END IF;
    IF EXISTS (
      SELECT 1
      FROM jsonb_array_elements(COALESCE(v_row.state_facts->'portal_captures', '[]'::jsonb)) e
      LEFT JOIN public.makesafe_portal_capture_revisions f
        ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
      WHERE f.id IS NULL
         OR f.makesafe_fact_version IS DISTINCT FROM (e->>'makesafe_fact_version')::bigint
         OR f.makesafe_content_hash IS DISTINCT FROM e->>'makesafe_content_hash'
         OR f.attendance_cycle_id IS DISTINCT FROM NULLIF(e->>'attendance_cycle_id', '')::uuid
    ) THEN RAISE EXCEPTION 'reconciliation row % portal facts changed', v_row.job_id; END IF;
    v_token := v_row.state_facts->'job';
    IF NOT EXISTS (
      SELECT 1 FROM public.jobs j
      WHERE j.id = v_row.job_id
        AND j.type IS NOT DISTINCT FROM v_token->>'type'
        AND j.status IS NOT DISTINCT FROM v_token->>'status'
        AND j.substatus IS NOT DISTINCT FROM v_token->>'substatus'
        AND j.metadata IS NOT DISTINCT FROM v_row.state_facts->'job_family'->'metadata'
    ) THEN
      RAISE EXCEPTION 'reconciliation row % job state changed', v_row.job_id;
    END IF;
    v_token := v_row.state_facts->'job_details';
    IF (SELECT count(*) FROM public.makesafe_job_details WHERE job_id = v_row.job_id)
      <> CASE WHEN v_token IS NULL THEN 0 ELSE 1 END
      OR (v_token IS NOT NULL AND NOT EXISTS (
        SELECT 1
        FROM public.makesafe_job_details d
        WHERE d.job_id = v_row.job_id
          AND d.substatus IS NOT DISTINCT FROM v_token->>'substatus'
          AND d.cycle_number IS NOT DISTINCT FROM (v_token->>'cycle_number')::integer
          AND d.attendance_cycle_id IS NOT DISTINCT FROM NULLIF(v_token->>'attendance_cycle_id', '')::uuid
          AND d.cycle_attribution IS NOT DISTINCT FROM v_token->>'cycle_attribution'
          AND d.report_type IS NOT DISTINCT FROM v_token->>'report_type'
          AND d.reopen_reason IS NOT DISTINCT FROM v_token->>'reopen_reason'
          AND d.reattend_count IS NOT DISTINCT FROM (v_token->>'reattend_count')::integer
          AND d.last_reattend_at IS NOT DISTINCT FROM (v_token->>'last_reattend_at')::timestamptz
          AND d.last_reattend_reason IS NOT DISTINCT FROM v_token->>'last_reattend_reason'
          AND d.cancel_reason IS NOT DISTINCT FROM v_token->>'cancel_reason'
          AND d.cancel_note IS NOT DISTINCT FROM v_token->>'cancel_note'
          AND d.cancelled_by IS NOT DISTINCT FROM v_token->>'cancelled_by'
          AND d.cancelled_at IS NOT DISTINCT FROM (v_token->>'cancelled_at')::timestamptz
          AND d.report_received_at IS NOT DISTINCT FROM (v_token->>'report_received_at')::timestamptz
          AND d.report_sent_at IS NOT DISTINCT FROM (v_token->>'report_sent_at')::timestamptz
          AND d.invoice_ready_at IS NOT DISTINCT FROM (v_token->>'invoice_ready_at')::timestamptz
          AND d.invoice_notes IS NOT DISTINCT FROM v_token->>'invoice_notes'
          AND d.safety_requirements IS NOT DISTINCT FROM v_token->>'safety_requirements'
          AND d.special_instructions IS NOT DISTINCT FROM v_token->>'special_instructions'
          AND d.external_links IS NOT DISTINCT FROM v_token->'external_links'
          AND d.billing_rules IS NOT DISTINCT FROM v_token->'billing_rules'
          AND d.portal_verified_at IS NOT DISTINCT FROM (v_token->>'portal_verified_at')::timestamptz
          AND d.portal_verified_cycle IS NOT DISTINCT FROM (v_token->>'portal_verified_cycle')::integer
          AND d.portal_verified_signal IS NOT DISTINCT FROM v_token->>'portal_verified_signal'
          AND d.portal_verified_by IS NOT DISTINCT FROM v_token->>'portal_verified_by'
          AND d.updated_at IS NOT DISTINCT FROM (v_token->>'updated_at')::timestamptz
      )) THEN
      RAISE EXCEPTION 'reconciliation row % job details changed', v_row.job_id;
    END IF;
    v_token := v_row.state_facts->'detail_cycle_binding';
    IF v_token->>'attendance_cycle_id' IS NOT NULL
       AND NOT EXISTS (
         SELECT 1
         FROM public.makesafe_attendance_cycles c
         WHERE c.id = (v_token->>'attendance_cycle_id')::uuid
           AND c.job_id = v_row.job_id
       ) THEN
      RAISE EXCEPTION 'reconciliation row % detail cycle binding changed', v_row.job_id;
    END IF;
    v_token := v_row.state_facts->'docket';
    IF (SELECT count(*) FROM public.makesafe_docket_revisions_current WHERE job_id = v_row.job_id)
      <> CASE WHEN v_token IS NULL THEN 0 ELSE 1 END
      OR (v_token IS NOT NULL AND NOT EXISTS (
        SELECT 1
        FROM public.makesafe_docket_revisions_current d
        WHERE d.job_id = v_row.job_id
          AND d.id IS NOT DISTINCT FROM (v_token->>'id')::uuid
          AND d.source_instruction_id IS NOT DISTINCT FROM v_token->>'source_instruction_id'
          AND d.lineage_id IS NOT DISTINCT FROM v_token->>'lineage_id'
          AND d.attendance_cycle_ids IS NOT DISTINCT FROM (
            SELECT COALESCE(array_agg(value::uuid), '{}'::uuid[])
            FROM jsonb_array_elements_text(COALESCE(v_token->'attendance_cycle_ids', '[]'::jsonb))
          )
          AND d.current_attendance_cycle_id IS NOT DISTINCT FROM (v_token->>'current_attendance_cycle_id')::uuid
          AND d.readiness_revision IS NOT DISTINCT FROM v_token->>'readiness_revision'
          AND d.input_content_hash IS NOT DISTINCT FROM v_token->>'input_content_hash'
          AND d.output_content_hash IS NOT DISTINCT FROM v_token->>'output_content_hash'
          AND d.state IS NOT DISTINCT FROM v_token->>'state'
          AND d.pre_xero_docs_ready IS NOT DISTINCT FROM (v_token->>'pre_xero_docs_ready')::boolean
          AND d.envelope IS NOT DISTINCT FROM v_token->'envelope'
          AND d.review_spec IS NOT DISTINCT FROM v_token->'review_spec'
          AND d.release_payload IS NOT DISTINCT FROM v_token->'release_payload'
          AND d.committed_at IS NOT DISTINCT FROM (v_token->>'committed_at')::timestamptz
      )) THEN
      RAISE EXCEPTION 'reconciliation row % docket facts changed', v_row.job_id;
    END IF;
    v_token := v_row.state_facts->'cases';
    IF (SELECT count(*) FROM public.makesafe_intake_cases WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_token, '[]'::jsonb))
      OR EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(v_token, '[]'::jsonb)) e
        LEFT JOIN public.makesafe_intake_cases f
          ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
        WHERE f.id IS NULL
           OR f.instruction_key IS DISTINCT FROM e->>'instruction_key'
           OR f.lineage_id IS DISTINCT FROM e->>'lineage_id'
           OR f.state IS DISTINCT FROM e->>'state'
           OR f.state_version IS DISTINCT FROM (e->>'state_version')::integer
           OR f.source_version IS DISTINCT FROM (e->>'source_version')::bigint
           OR f.source_content_hash IS DISTINCT FROM e->>'source_content_hash'
           OR f.lineage_version IS DISTINCT FROM (e->>'lineage_version')::bigint
           OR f.lineage_correction_hash IS DISTINCT FROM e->>'lineage_correction_hash'
           OR f.lineage_supersession_hash IS DISTINCT FROM e->>'lineage_supersession_hash'
           OR f.updated_at IS DISTINCT FROM (e->>'updated_at')::timestamptz
      )
    THEN RAISE EXCEPTION 'reconciliation row % intake-case facts changed', v_row.job_id; END IF;
    v_token := v_row.state_facts->'holds';
    IF (SELECT count(*) FROM public.makesafe_status_holds WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_token, '[]'::jsonb))
      OR EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(v_token, '[]'::jsonb)) e
        LEFT JOIN public.makesafe_status_holds f
          ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
        WHERE f.id IS NULL
           OR f.attendance_cycle_id IS DISTINCT FROM NULLIF(e->>'attendance_cycle_id', '')::uuid
           OR f.blocker_code IS DISTINCT FROM e->>'blocker_code'
           OR f.owner_role IS DISTINCT FROM e->>'owner_role'
           OR f.recovery_action IS DISTINCT FROM e->>'recovery_action'
           OR f.recovery_instruction IS DISTINCT FROM e->>'recovery_instruction'
           OR f.evidence_refs IS DISTINCT FROM e->'evidence_refs'
           OR f.created_at IS DISTINCT FROM (e->>'created_at')::timestamptz
           OR f.lifted_at IS DISTINCT FROM (e->>'lifted_at')::timestamptz
           OR f.note IS DISTINCT FROM e->>'note'
      )
    THEN RAISE EXCEPTION 'reconciliation row % hold facts changed', v_row.job_id; END IF;
    v_token := v_row.state_facts->'family_rule';
    IF v_token IS NULL THEN
      IF EXISTS (
        SELECT 1
        FROM public.makesafe_family_rules_current_v2 f
        JOIN public.makesafe_state_identity_current_v2 i
          ON i.job_id = v_row.job_id
         AND i.family_rule_key = f.family_code
      ) THEN
        RAISE EXCEPTION 'reconciliation row % family rule changed', v_row.job_id;
      END IF;
    ELSIF NOT EXISTS (
      SELECT 1
      FROM public.makesafe_family_rules_current_v2 f
      JOIN public.makesafe_state_identity_current_v2 i
        ON i.job_id = v_row.job_id
       AND i.family_rule_key = f.family_code
      WHERE f.family_code IS NOT DISTINCT FROM v_token->>'family_code'
        AND f.family_kind IS NOT DISTINCT FROM v_token->>'family_kind'
        AND f.matrix_revision IS NOT DISTINCT FROM v_token->>'matrix_revision'
        AND f.matrix_content_hash IS NOT DISTINCT FROM v_token->>'matrix_content_hash'
        AND f.completion_photo_floor IS NOT DISTINCT FROM (v_token->>'completion_photo_floor')::integer
        AND f.required_document_types IS NOT DISTINCT FROM (
          SELECT COALESCE(array_agg(value), '{}'::text[])
          FROM jsonb_array_elements_text(COALESCE(v_token->'required_document_types', '[]'::jsonb))
        )
        AND f.required_portal_roles IS NOT DISTINCT FROM (
          SELECT COALESCE(array_agg(value), '{}'::text[])
          FROM jsonb_array_elements_text(COALESCE(v_token->'required_portal_roles', '[]'::jsonb))
        )
    ) THEN
      RAISE EXCEPTION 'reconciliation row % family rule changed', v_row.job_id;
    END IF;
    v_token := v_row.state_facts->'cancellations';
    IF (SELECT count(*) FROM public.makesafe_cancellation_current_v2 WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_token, '[]'::jsonb))
      OR EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(v_token, '[]'::jsonb)) e
        LEFT JOIN public.makesafe_cancellation_current_v2 f
          ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
        WHERE f.id IS NULL
           OR f.attendance_cycle_set_hash IS DISTINCT FROM e->>'attendance_cycle_set_hash'
           OR f.state IS DISTINCT FROM e->>'state'
           OR f.reason_code IS DISTINCT FROM e->>'reason_code'
           OR f.note IS DISTINCT FROM e->>'note'
           OR f.decided_by IS DISTINCT FROM e->>'decided_by'
           OR f.decided_at IS DISTINCT FROM (e->>'decided_at')::timestamptz
      )
    THEN RAISE EXCEPTION 'reconciliation row % cancellation facts changed', v_row.job_id; END IF;
    v_token := v_row.state_facts->'terminal_proofs';
    IF (SELECT count(*) FROM public.makesafe_terminal_proofs_current_v2 WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_token, '[]'::jsonb))
      OR EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(v_token, '[]'::jsonb)) e
        LEFT JOIN public.makesafe_terminal_proofs_current_v2 f
          ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
        WHERE f.id IS NULL
           OR f.kind IS DISTINCT FROM e->>'kind'
           OR f.attendance_cycle_ids IS DISTINCT FROM (
             SELECT COALESCE(array_agg(value::uuid), '{}'::uuid[])
             FROM jsonb_array_elements_text(COALESCE(e->'attendance_cycle_ids', '[]'::jsonb))
           )
           OR f.readiness_revision IS DISTINCT FROM e->>'readiness_revision'
           OR f.release_revision_id IS DISTINCT FROM NULLIF(e->>'release_revision_id', '')::uuid
           OR f.closeout_revision_id IS DISTINCT FROM NULLIF(e->>'closeout_revision_id', '')::uuid
           OR f.proven_at IS DISTINCT FROM (e->>'proven_at')::timestamptz
      )
    THEN RAISE EXCEPTION 'reconciliation row % terminal proof facts changed', v_row.job_id; END IF;
    v_token := v_row.state_facts->'pack_cycles';
    IF (SELECT count(*) FROM public.makesafe_report_pack_cycles WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_token, '[]'::jsonb))
      OR EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(v_token, '[]'::jsonb)) e
        LEFT JOIN public.makesafe_report_pack_cycles f
          ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
        WHERE f.id IS NULL
           OR f.pack_id IS DISTINCT FROM (e->>'pack_id')::uuid
           OR f.attendance_cycle_id IS DISTINCT FROM (e->>'attendance_cycle_id')::uuid
           OR f.cycle_attribution IS DISTINCT FROM e->>'cycle_attribution'
      )
    THEN RAISE EXCEPTION 'reconciliation row % pack-cycle facts changed', v_row.job_id; END IF;
    v_token := v_row.state_facts->'packs';
    IF (SELECT count(*) FROM public.makesafe_report_packs WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_token, '[]'::jsonb))
      OR EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(v_token, '[]'::jsonb)) e
        LEFT JOIN public.makesafe_report_packs f
          ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
        WHERE f.id IS NULL
           OR f.status IS DISTINCT FROM e->>'status'
           OR f.review_state IS DISTINCT FROM e->>'review_state'
           OR f.needs_money_review IS DISTINCT FROM (e->>'needs_money_review')::boolean
           OR f.last_render_hash IS DISTINCT FROM e->>'last_render_hash'
           OR f.makesafe_fact_version IS DISTINCT FROM (e->>'makesafe_fact_version')::bigint
           OR f.makesafe_content_hash IS DISTINCT FROM e->>'makesafe_content_hash'
      )
    THEN RAISE EXCEPTION 'reconciliation row % pack facts changed', v_row.job_id; END IF;
    v_token := v_row.state_facts->'approvals';
    IF (SELECT count(*) FROM public.makesafe_revision_approvals WHERE job_id = v_row.job_id)
      <> jsonb_array_length(COALESCE(v_token, '[]'::jsonb))
      OR EXISTS (
        SELECT 1
        FROM jsonb_array_elements(COALESCE(v_token, '[]'::jsonb)) e
        LEFT JOIN public.makesafe_revision_approvals f
          ON f.id = (e->>'id')::uuid AND f.job_id = v_row.job_id
        WHERE f.id IS NULL
           OR f.action IS DISTINCT FROM e->>'action'
           OR f.decision IS DISTINCT FROM e->>'decision'
           OR f.readiness_revision IS DISTINCT FROM e->>'readiness_revision'
           OR f.dependency_generation IS DISTINCT FROM (e->>'dependency_generation')::integer
           OR f.docket_revision_id IS DISTINCT FROM NULLIF(e->>'docket_revision_id', '')::uuid
           OR f.release_revision_id IS DISTINCT FROM NULLIF(e->>'release_revision_id', '')::uuid
           OR f.decided_at IS DISTINCT FROM (e->>'decided_at')::timestamptz
      )
    THEN RAISE EXCEPTION 'reconciliation row % approval facts changed', v_row.job_id; END IF;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.discard_makesafe_board_reconciliation(
  p_run_key text,
  p_selection_hash text,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE v_deleted integer;
BEGIN
  DELETE FROM public.makesafe_board_reconciliation_staged_chunks
  WHERE run_key = p_run_key
    AND (p_selection_hash IS NULL OR selection_hash = p_selection_hash);
  GET DIAGNOSTICS v_deleted = ROW_COUNT;
  RETURN jsonb_build_object('ok', true, 'run_key', p_run_key,
    'discarded_chunks', v_deleted, 'reason', left(COALESCE(p_reason, ''), 500));
END;
$$;

