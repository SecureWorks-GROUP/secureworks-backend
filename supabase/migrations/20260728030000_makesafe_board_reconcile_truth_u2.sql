CREATE OR REPLACE FUNCTION public.seed_makesafe_state_authority_v1(
  p_run_key text,
  p_applied_by text,
  p_selection_hash text,
  p_job_ids uuid[]
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, extensions
AS $$
DECLARE
  v_requested integer;
  v_matched integer;
  v_identity_count integer;
  v_cycle_count integer;
  v_fact_count integer := 0;
  v_terminal_count integer;
  v_cancellation_count integer;
  v_family_resolved integer;
  v_family_unresolved integer;
  v_result jsonb;
  v_existing public.makesafe_state_seed_runs%ROWTYPE;
BEGIN
  IF length(btrim(COALESCE(p_run_key, ''))) = 0
     OR length(btrim(COALESCE(p_applied_by, ''))) = 0
     OR COALESCE(p_selection_hash, '') !~ '^sha256:[0-9a-f]{64}$' THEN
    RAISE EXCEPTION
      'run key, attribution, and sha256 selection hash are required';
  END IF;
  v_requested := cardinality(p_job_ids);
  IF v_requested < 1 OR v_requested > 500 THEN
    RAISE EXCEPTION 'p_job_ids must contain between 1 and 500 jobs';
  END IF;
  IF v_requested <> (
    SELECT count(DISTINCT id) FROM unnest(p_job_ids) ids(id)
  ) THEN
    RAISE EXCEPTION 'p_job_ids contains duplicate jobs';
  END IF;

  SELECT * INTO v_existing
  FROM public.makesafe_state_seed_runs
  WHERE run_key = p_run_key;
  IF FOUND THEN
    IF v_existing.selection_hash IS DISTINCT FROM p_selection_hash THEN
      RAISE EXCEPTION 'seed run key already belongs to a different selection';
    END IF;
    RETURN v_existing.result_json ||
      jsonb_build_object('idempotent_replay', true);
  END IF;

  SELECT count(*) INTO v_matched
  FROM public.jobs j
  WHERE j.id = ANY(p_job_ids)
    AND j.type = 'makesafe';
  IF v_matched <> v_requested THEN
    RAISE EXCEPTION 'seed selection contains a missing or non-make-safe job';
  END IF;

  -- Publish the five family shapes sealed by U4. Job binding below still fails
  -- closed when the stored evidence cannot distinguish a family or builder
  -- applicability; publishing a rule is not permission to guess a binding.
  WITH seeds AS (
    SELECT *
    FROM (VALUES
      (
        'physical_makesafe'::text,
        'physical'::text,
        'ses-builder-family-matrix/2026-07-27.1:physical_makesafe',
        5::integer,
        ARRAY[]::text[],
        ARRAY[]::text[]
      ),
      (
        'temporary_fencing',
        'physical',
        'ses-builder-family-matrix/2026-07-27.1:temporary_fencing',
        5,
        ARRAY[]::text[],
        ARRAY[]::text[]
      ),
      (
        'ordinary_roof_portal',
        'portal',
        'ses-builder-family-matrix/2026-07-27.1:ordinary_roof_portal',
        0,
        ARRAY[]::text[],
        ARRAY['roof_report']::text[]
      ),
      (
        'own_template_roof',
        'report_only',
        'ses-builder-family-matrix/2026-07-27.1:own_template_roof',
        0,
        ARRAY['roof_report']::text[],
        ARRAY[]::text[]
      ),
      (
        'assessment_quote',
        'portal',
        'ses-builder-family-matrix/2026-07-27.1:assessment_quote',
        0,
        ARRAY[]::text[],
        ARRAY['assessment', 'photos', 'scope']::text[]
      )
    ) AS s(
      family_code,
      family_kind,
      matrix_revision,
      completion_photo_floor,
      required_document_types,
      required_portal_roles
    )
  ),
  inserted AS (
    INSERT INTO public.makesafe_family_rule_revisions (
      family_code,
      family_kind,
      matrix_revision,
      matrix_content_hash,
      completion_photo_floor,
      required_document_types,
      required_portal_roles,
      created_by
    )
    SELECT
      s.family_code,
      s.family_kind,
      s.matrix_revision,
      public.makesafe_fact_hash_v1(
        'family-rule',
        jsonb_build_object(
          'family_code', s.family_code,
          'family_kind', s.family_kind,
          'matrix_revision', s.matrix_revision,
          'completion_photo_floor', s.completion_photo_floor,
          'required_document_types', to_jsonb(s.required_document_types),
          'required_portal_roles', to_jsonb(s.required_portal_roles)
        )
      ),
      s.completion_photo_floor,
      s.required_document_types,
      s.required_portal_roles,
      p_applied_by
    FROM seeds s
    ON CONFLICT (family_code, matrix_revision) DO NOTHING
    RETURNING id
  )
  SELECT count(*) INTO v_fact_count FROM inserted;

  INSERT INTO public.makesafe_family_rule_current (
    family_code, revision_id, updated_by
  )
  SELECT r.family_code, r.id, p_applied_by
  FROM public.makesafe_family_rule_revisions r
  WHERE r.matrix_revision IN (
    'ses-builder-family-matrix/2026-07-27.1:physical_makesafe',
    'ses-builder-family-matrix/2026-07-27.1:temporary_fencing',
    'ses-builder-family-matrix/2026-07-27.1:ordinary_roof_portal',
    'ses-builder-family-matrix/2026-07-27.1:own_template_roof',
    'ses-builder-family-matrix/2026-07-27.1:assessment_quote'
  )
  ON CONFLICT (family_code) DO UPDATE
  SET revision_id = EXCLUDED.revision_id,
      updated_at = transaction_timestamp(),
      updated_by = EXCLUDED.updated_by
  WHERE makesafe_family_rule_current.revision_id IS DISTINCT FROM
    EXCLUDED.revision_id;

  WITH inserted AS (
    INSERT INTO public.makesafe_attendance_cycles (
      job_id, cycle_number, opened_at, open_reason
    )
    SELECT
      j.id,
      GREATEST(COALESCE(d.cycle_number, 1), 1),
      COALESCE(d.created_at, j.created_at, transaction_timestamp()),
      'state_authority_seed_existing_job'
    FROM public.jobs j
    LEFT JOIN public.makesafe_job_details d ON d.job_id = j.id
    WHERE j.id = ANY(p_job_ids)
      AND NOT EXISTS (
        SELECT 1 FROM public.makesafe_attendance_cycles c
        WHERE c.job_id = j.id
      )
    ON CONFLICT (job_id, cycle_number) DO NOTHING
    RETURNING id
  )
  SELECT count(*) INTO v_cycle_count FROM inserted;

  WITH single_cycle AS (
    SELECT job_id, (array_agg(id ORDER BY id))[1] AS cycle_id
    FROM public.makesafe_attendance_cycles
    WHERE job_id = ANY(p_job_ids)
    GROUP BY job_id
    HAVING count(*) = 1
  )
  UPDATE public.makesafe_job_details d
  SET attendance_cycle_id = s.cycle_id,
      cycle_attribution = 'bound',
      updated_at = transaction_timestamp()
  FROM single_cycle s
  WHERE d.job_id = s.job_id
    AND (
      d.attendance_cycle_id IS DISTINCT FROM s.cycle_id
      OR d.cycle_attribution IS DISTINCT FROM 'bound'
    );

  WITH single_cycle AS (
    SELECT job_id, (array_agg(id ORDER BY id))[1] AS cycle_id
    FROM public.makesafe_attendance_cycles
    WHERE job_id = ANY(p_job_ids)
    GROUP BY job_id
    HAVING count(*) = 1
  ),
  updated AS (
    UPDATE public.job_assignments f
    SET attendance_cycle_id = s.cycle_id,
        cycle_attribution = 'bound'
    FROM single_cycle s
    WHERE f.job_id = s.job_id
      AND (
        f.attendance_cycle_id IS DISTINCT FROM s.cycle_id
        OR f.cycle_attribution IS DISTINCT FROM 'bound'
      )
    RETURNING f.id
  )
  SELECT v_fact_count + count(*) INTO v_fact_count FROM updated;

  WITH exact_cycle AS (
    SELECT r.id AS report_id, c.id AS cycle_id
    FROM public.job_service_reports r
    JOIN public.makesafe_attendance_cycles c
      ON c.job_id = r.job_id
     AND c.cycle_number = COALESCE(r.cycle_number, 1)
    WHERE r.job_id = ANY(p_job_ids)
  ),
  updated AS (
    UPDATE public.job_service_reports f
    SET attendance_cycle_id = e.cycle_id,
        cycle_attribution = 'bound'
    FROM exact_cycle e
    WHERE f.id = e.report_id
      AND (
        f.attendance_cycle_id IS DISTINCT FROM e.cycle_id
        OR f.cycle_attribution IS DISTINCT FROM 'bound'
      )
    RETURNING f.id
  )
  SELECT v_fact_count + count(*) INTO v_fact_count FROM updated;

  WITH single_cycle AS (
    SELECT job_id, (array_agg(id ORDER BY id))[1] AS cycle_id
    FROM public.makesafe_attendance_cycles
    WHERE job_id = ANY(p_job_ids)
    GROUP BY job_id
    HAVING count(*) = 1
  ),
  updated_docs AS (
    UPDATE public.job_documents f
    SET attendance_cycle_id = s.cycle_id,
        cycle_attribution = 'bound'
    FROM single_cycle s
    WHERE f.job_id = s.job_id
      AND (
        f.attendance_cycle_id IS DISTINCT FROM s.cycle_id
        OR f.cycle_attribution IS DISTINCT FROM 'bound'
      )
    RETURNING f.id
  )
  SELECT v_fact_count + count(*) INTO v_fact_count FROM updated_docs;

  WITH single_cycle AS (
    SELECT job_id, (array_agg(id ORDER BY id))[1] AS cycle_id
    FROM public.makesafe_attendance_cycles
    WHERE job_id = ANY(p_job_ids)
    GROUP BY job_id
    HAVING count(*) = 1
  ),
  updated_media AS (
    UPDATE public.job_media f
    SET attendance_cycle_id = s.cycle_id,
        cycle_attribution = 'bound'
    FROM single_cycle s
    WHERE f.job_id = s.job_id
      AND (
        f.attendance_cycle_id IS DISTINCT FROM s.cycle_id
        OR f.cycle_attribution IS DISTINCT FROM 'bound'
      )
    RETURNING f.id
  )
  SELECT v_fact_count + count(*) INTO v_fact_count FROM updated_media;

  WITH inserted AS (
    INSERT INTO public.makesafe_report_pack_cycles (
      pack_id, job_id, attendance_cycle_id, cycle_attribution
    )
    SELECT p.id, p.job_id, s.cycle_id, 'bound'
    FROM public.makesafe_report_packs p
    JOIN (
      SELECT job_id, (array_agg(id ORDER BY id))[1] AS cycle_id
      FROM public.makesafe_attendance_cycles
      WHERE job_id = ANY(p_job_ids)
      GROUP BY job_id
      HAVING count(*) = 1
    ) s ON s.job_id = p.job_id
    WHERE NOT EXISTS (
      SELECT 1 FROM public.makesafe_report_pack_cycles pc
      WHERE pc.pack_id = p.id
    )
    ON CONFLICT (pack_id, attendance_cycle_id) DO NOTHING
    RETURNING id
  )
  SELECT v_fact_count + count(*) INTO v_fact_count FROM inserted;

  -- Touch every selected fact once. The BEFORE triggers compute the canonical
  -- hash and v1 version; no-op future writes preserve both.
  UPDATE public.makesafe_attendance_cycles
  SET makesafe_fact_version = makesafe_fact_version
  WHERE job_id = ANY(p_job_ids)
    AND (makesafe_fact_version IS NULL OR makesafe_content_hash IS NULL);
  GET DIAGNOSTICS v_matched = ROW_COUNT;
  v_fact_count := v_fact_count + v_matched;

  UPDATE public.job_assignments
  SET makesafe_fact_version = makesafe_fact_version
  WHERE job_id = ANY(p_job_ids)
    AND (makesafe_fact_version IS NULL OR makesafe_content_hash IS NULL);
  GET DIAGNOSTICS v_matched = ROW_COUNT;
  v_fact_count := v_fact_count + v_matched;

  UPDATE public.job_service_reports
  SET makesafe_fact_version = makesafe_fact_version
  WHERE job_id = ANY(p_job_ids)
    AND (makesafe_fact_version IS NULL OR makesafe_content_hash IS NULL);
  GET DIAGNOSTICS v_matched = ROW_COUNT;
  v_fact_count := v_fact_count + v_matched;

  UPDATE public.job_documents
  SET makesafe_fact_version = makesafe_fact_version
  WHERE job_id = ANY(p_job_ids)
    AND (makesafe_fact_version IS NULL OR makesafe_content_hash IS NULL);
  GET DIAGNOSTICS v_matched = ROW_COUNT;
  v_fact_count := v_fact_count + v_matched;

  UPDATE public.job_media
  SET makesafe_fact_version = makesafe_fact_version
  WHERE job_id = ANY(p_job_ids)
    AND (makesafe_fact_version IS NULL OR makesafe_content_hash IS NULL);
  GET DIAGNOSTICS v_matched = ROW_COUNT;
  v_fact_count := v_fact_count + v_matched;

  UPDATE public.makesafe_report_packs
  SET makesafe_fact_version = makesafe_fact_version
  WHERE job_id = ANY(p_job_ids)
    AND (makesafe_fact_version IS NULL OR makesafe_content_hash IS NULL);
  GET DIAGNOSTICS v_matched = ROW_COUNT;
  v_fact_count := v_fact_count + v_matched;

  WITH selected_cases AS (
    SELECT
      c.*,
      count(*) OVER (
        PARTITION BY COALESCE(c.target_job_id, c.job_id)
      ) AS case_count
    FROM public.makesafe_intake_cases c
    WHERE (
        c.job_id = ANY(p_job_ids)
        OR c.target_job_id = ANY(p_job_ids)
      )
      AND c.state IN ('confirmed_live_job', 'blocked_live_job')
  )
  UPDATE public.makesafe_intake_cases c
  SET source_version = COALESCE(c.source_version, 1),
      source_content_hash = COALESCE(
        c.source_content_hash,
        public.makesafe_fact_hash_v1(
          'intake-source',
          jsonb_build_object(
            'case_id', c.id,
            'instruction_key', c.instruction_key,
            'source_fingerprint', c.source_fingerprint,
            'raw_identity_json', c.raw_identity_json,
            'received_at', c.received_at
          )
        )
      ),
      lineage_version = COALESCE(c.lineage_version, 1),
      lineage_correction_hash = COALESCE(
        c.lineage_correction_hash,
        public.makesafe_fact_hash_v1(
          'lineage-corrections',
          jsonb_build_object(
            'case_id', c.id,
            'case_corrections', COALESCE((
              SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at, x.id)
              FROM public.makesafe_intake_case_authority_corrections x
              WHERE x.legacy_case_id = c.id OR x.effective_case_id = c.id
            ), '[]'::jsonb),
            'source_corrections', COALESCE((
              SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at, x.id)
              FROM public.makesafe_intake_source_authority_corrections x
              WHERE x.legacy_case_id = c.id OR x.effective_case_id = c.id
            ), '[]'::jsonb)
          )
        )
      ),
      lineage_supersession_hash = COALESCE(
        c.lineage_supersession_hash,
        public.makesafe_fact_hash_v1(
          'lineage-supersessions',
          jsonb_build_object(
            'case_id', c.id,
            'supersessions', COALESCE((
              SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at, x.id)
              FROM
                public.makesafe_intake_source_authority_correction_supersessions
                  x
              WHERE x.prior_authority_case_id = c.id
                 OR x.effective_case_id = c.id
            ), '[]'::jsonb)
          )
        )
      )
  FROM selected_cases s
  WHERE c.id = s.id;

  WITH job_inputs AS (
    SELECT
      j.*,
      d.external_ref AS detail_external_ref,
      d.report_type,
      lower(COALESCE(d.requesting_company_slug, '')) AS company_slug,
      lower(concat_ws(
        ' ',
        d.requesting_company_slug,
        d.requesting_company_name,
        d.external_ref,
        j.metadata->'requesting_company'->>'slug',
        j.metadata->'requesting_company'->>'name'
      )) AS builder_token,
      lower(COALESCE(
        j.metadata->>'ses_family',
        j.metadata->>'makesafe_job_family',
        j.metadata->>'makesafe_family',
        j.metadata->>'job_family',
        d.report_type,
        ''
      )) AS family_token
    FROM public.jobs j
    LEFT JOIN public.makesafe_job_details d ON d.job_id = j.id
    WHERE j.id = ANY(p_job_ids)
  ),
  job_context AS (
    SELECT
      i.*,
      CASE
        WHEN (
          i.builder_token ~ '(^|[^a-z0-9])(aj|ajs|ajbr)([^a-z0-9]|$)'
          OR i.builder_token LIKE '%alliance joinery%'
        )
          AND i.family_token NOT LIKE '%temp%fenc%'
          THEN 'physical_makesafe'
        WHEN i.family_token LIKE '%temp%fenc%'
          THEN 'temporary_fencing'
        WHEN i.family_token LIKE '%assessment%'
          OR i.family_token LIKE '%report_and_quote%'
          THEN 'assessment_quote'
        WHEN i.family_token LIKE '%roof%'
          AND (
            i.metadata->>'own_template_requested' = 'true'
            OR lower(COALESCE(i.metadata->>'report_delivery', '')) =
              'own_document'
            OR i.family_token LIKE '%own%template%'
            OR i.family_token LIKE '%strata%'
          )
          THEN 'own_template_roof'
        WHEN i.family_token LIKE '%roof%'
          AND (
            i.builder_token ~ '(^|[^a-z0-9])mlb([^a-z0-9]|$)'
            OR i.builder_token LIKE '%ml builders%'
            OR i.builder_token LIKE '%major loss builders%'
            OR i.builder_token LIKE '%mlbuilders%'
          )
          THEN 'ordinary_roof_portal'
        WHEN i.family_token IN (
          'general_makesafe',
          'physical_makesafe',
          'makesafe'
        )
          THEN 'physical_makesafe'
        ELSE NULL
      END AS family_code
    FROM job_inputs i
  ),
  case_candidates AS (
    SELECT
      j.id AS job_id,
      c.id AS case_id
    FROM job_context j
    JOIN public.makesafe_intake_cases c
      ON c.job_id = j.id OR c.target_job_id = j.id
    WHERE c.state IN ('confirmed_live_job', 'blocked_live_job')
  ),
  case_counts AS (
    SELECT
      j.id AS job_id,
      count(c.id) AS case_count,
      (array_agg(c.id ORDER BY c.id))[1] AS case_id
    FROM job_context j
    LEFT JOIN case_candidates c ON c.job_id = j.id
    GROUP BY j.id
  ),
  source_rows AS (
    SELECT
      j.org_id,
      j.id AS job_id,
      CASE
        WHEN cc.case_count = 1 THEN 'effective_intake_case'
        WHEN cc.case_count = 0 THEN 'legacy_job_record'
        ELSE 'unresolved_authority'
      END AS authority_kind,
      CASE WHEN cc.case_count = 1 THEN c.id ELSE NULL END AS effective_case_id,
      CASE
        WHEN cc.case_count = 1 THEN c.instruction_key
        WHEN cc.case_count = 0 THEN 'legacy-job:' || j.id::text
        ELSE 'unresolved-job:' || j.id::text
      END AS source_instruction_id,
      COALESCE(c.source_version, 1) AS source_version,
      COALESCE(
        c.source_content_hash,
        public.makesafe_fact_hash_v1(
          'legacy-job-source',
          jsonb_build_object(
            'job_id', j.id,
            'job_number', j.job_number,
            'external_ref', j.detail_external_ref,
            'created_at', j.created_at
          )
        )
      ) AS source_content_hash,
      COALESCE(c.lineage_id::text, j.id::text) AS lineage_id,
      COALESCE(c.lineage_version, 1) AS lineage_version,
      COALESCE(
        c.lineage_correction_hash,
        public.makesafe_fact_hash_v1(
          'legacy-lineage-corrections',
          jsonb_build_object('job_id', j.id, 'corrections', '[]'::jsonb)
        )
      ) AS lineage_correction_hash,
      COALESCE(
        c.lineage_supersession_hash,
        public.makesafe_fact_hash_v1(
          'legacy-lineage-supersessions',
          jsonb_build_object('job_id', j.id, 'supersessions', '[]'::jsonb)
        )
      ) AS lineage_supersession_hash,
      CASE
        WHEN cc.case_count > 1 THEN 'blocked_live_job'
        ELSE c.state
      END AS intake_state,
      CASE
        WHEN j.family_code IS NOT NULL THEN 'resolved'
        ELSE 'unresolved'
      END AS family_state,
      j.family_code AS family_rule_key,
      CASE
        WHEN cc.case_count > 1 THEN 'multiple_effective_authorities'
        WHEN j.family_token LIKE '%roof%'
          THEN 'builder_family_applicability_unresolved'
        WHEN j.family_code IS NULL THEN 'family_unclassified'
        ELSE NULL
      END AS blocker_code,
      CASE
        WHEN cc.case_count > 1
          THEN 'Choose the one source instruction that owns this job.'
        WHEN j.family_token LIKE '%roof%'
          THEN 'Confirm the builder and whether this roof report is a portal handoff or our own document.'
        WHEN j.family_code IS NULL
          THEN 'Classify the job family from its original work-order evidence.'
        ELSE NULL
      END AS recovery_instruction,
      jsonb_build_array(
        'jobs:' || j.id::text,
        CASE
          WHEN c.id IS NOT NULL
            THEN 'makesafe_intake_cases:' || c.id::text
          ELSE 'makesafe_job_details:' || j.id::text
        END
      ) AS evidence_refs
    FROM job_context j
    JOIN case_counts cc ON cc.job_id = j.id
    LEFT JOIN public.makesafe_intake_cases c ON c.id = cc.case_id
  ),
  revision_rows AS (
    SELECT
      s.*,
      public.makesafe_fact_hash_v1(
        'state-identity-revision',
        jsonb_build_object(
          'job_id', s.job_id,
          'authority_kind', s.authority_kind,
          'effective_case_id', s.effective_case_id,
          'source_instruction_id', s.source_instruction_id,
          'source_version', s.source_version,
          'source_content_hash', s.source_content_hash,
          'lineage_id', s.lineage_id,
          'lineage_version', s.lineage_version,
          'lineage_correction_hash', s.lineage_correction_hash,
          'lineage_supersession_hash', s.lineage_supersession_hash,
          'intake_state', s.intake_state,
          'family_state', s.family_state,
          'family_rule_key', s.family_rule_key,
          'blocker_code', s.blocker_code,
          'evidence_refs', s.evidence_refs
        )
      ) AS revision_hash
    FROM source_rows s
  ),
  inserted AS (
    INSERT INTO public.makesafe_state_identity_revisions (
      org_id,
      job_id,
      authority_kind,
      effective_case_id,
      source_instruction_id,
      source_version,
      source_content_hash,
      lineage_id,
      lineage_version,
      lineage_correction_hash,
      lineage_supersession_hash,
      intake_state,
      family_state,
      family_rule_key,
      blocker_code,
      recovery_instruction,
      evidence_refs,
      revision_hash,
      created_by
    )
    SELECT
      r.org_id,
      r.job_id,
      r.authority_kind,
      r.effective_case_id,
      r.source_instruction_id,
      r.source_version,
      r.source_content_hash,
      r.lineage_id,
      r.lineage_version,
      r.lineage_correction_hash,
      r.lineage_supersession_hash,
      r.intake_state,
      r.family_state,
      r.family_rule_key,
      r.blocker_code,
      r.recovery_instruction,
      r.evidence_refs,
      r.revision_hash,
      p_applied_by
    FROM revision_rows r
    ON CONFLICT (job_id, revision_hash) DO NOTHING
    RETURNING id
  )
  SELECT count(*) INTO v_identity_count FROM inserted;

  WITH cycle_sets AS (
    SELECT
      j.id AS job_id,
      j.org_id,
      array_agg(c.id ORDER BY c.id) AS cycle_ids,
      public.makesafe_attendance_cycle_set_hash_v1(
        array_agg(c.id ORDER BY c.id)
      ) AS cycle_set_hash
    FROM public.jobs j
    JOIN public.makesafe_attendance_cycles c ON c.job_id = j.id
    WHERE j.id = ANY(p_job_ids)
    GROUP BY j.id, j.org_id
  ),
  closeout AS (
    SELECT DISTINCT ON (p.job_id)
      p.job_id,
      p.id AS pack_id,
      COALESCE(
        NULLIF(upper(p.invoice_status), ''),
        upper(x.status)
      ) AS invoice_status,
      p.xero_invoice_id,
      x.id AS invoice_id,
      p.sent_at
    FROM public.makesafe_report_packs p
    LEFT JOIN public.xero_invoices x
      ON x.job_id = p.job_id
     AND x.invoice_type = 'ACCREC'
     AND upper(x.status) IN ('AUTHORISED', 'PAID')
    WHERE p.job_id = ANY(p_job_ids)
      AND COALESCE(p.pack_kind, 'main') = 'main'
      AND lower(COALESCE(p.status, '')) IN (
        'sent', 'sent_marker_failed', 'sent_not_closed', 'close_failed'
      )
      AND COALESCE(NULLIF(upper(p.invoice_status), ''), upper(x.status))
        IN ('AUTHORISED', 'PAID')
    ORDER BY p.job_id, p.sent_at DESC NULLS LAST, p.id DESC
  ),
  inserted AS (
    INSERT INTO public.makesafe_terminal_proofs (
      org_id,
      job_id,
      kind,
      attendance_cycle_ids,
      attendance_cycle_set_hash,
      evidence_refs,
      proven_by,
      proven_at
    )
    SELECT
      cs.org_id,
      cs.job_id,
      'verified_historical_closeout',
      cs.cycle_ids,
      cs.cycle_set_hash,
      to_jsonb(array_remove(ARRAY[
        'makesafe_report_packs:' || co.pack_id::text,
        CASE WHEN co.invoice_id IS NOT NULL
          THEN 'xero_invoices:' || co.invoice_id::text END,
        CASE WHEN co.xero_invoice_id IS NOT NULL
          THEN 'xero_invoice_id:' || co.xero_invoice_id END
      ]::text[], NULL)),
      p_applied_by,
      COALESCE(co.sent_at, transaction_timestamp())
    FROM cycle_sets cs
    JOIN closeout co ON co.job_id = cs.job_id
    WHERE NOT EXISTS (
      SELECT 1
      FROM public.makesafe_terminal_proofs p
      WHERE p.job_id = cs.job_id
        AND p.kind = 'verified_historical_closeout'
        AND p.attendance_cycle_set_hash = cs.cycle_set_hash
    )
    RETURNING id
  )
  SELECT count(*) INTO v_terminal_count FROM inserted;

  WITH cycle_sets AS (
    SELECT
      j.id AS job_id,
      j.org_id,
      array_agg(c.id ORDER BY c.id) AS cycle_ids,
      public.makesafe_attendance_cycle_set_hash_v1(
        array_agg(c.id ORDER BY c.id)
      ) AS cycle_set_hash
    FROM public.jobs j
    JOIN public.makesafe_attendance_cycles c ON c.job_id = j.id
    WHERE j.id = ANY(p_job_ids)
    GROUP BY j.id, j.org_id
  ),
  inserted AS (
    INSERT INTO public.makesafe_cancellation_decisions (
      org_id,
      job_id,
      attendance_cycle_set_hash,
      state,
      reason_code,
      note,
      decided_by,
      decided_at,
      evidence_refs
    )
    SELECT
      cs.org_id,
      cs.job_id,
      cs.cycle_set_hash,
      'confirmed',
      d.cancel_reason,
      d.cancel_note,
      COALESCE(NULLIF(d.cancelled_by, ''), p_applied_by),
      COALESCE(d.cancelled_at, j.updated_at, transaction_timestamp()),
      jsonb_build_array(
        'jobs:' || j.id::text,
        'makesafe_job_details:' || d.job_id::text
      )
    FROM cycle_sets cs
    JOIN public.jobs j ON j.id = cs.job_id
    JOIN public.makesafe_job_details d ON d.job_id = cs.job_id
    WHERE lower(j.status) IN ('cancelled', 'canceled')
      AND length(btrim(COALESCE(d.cancel_reason, ''))) > 0
      AND d.cancelled_at IS NOT NULL
      AND NOT EXISTS (
        SELECT 1
        FROM public.makesafe_cancellation_decisions existing
        WHERE existing.job_id = cs.job_id
          AND existing.state = 'confirmed'
          AND existing.attendance_cycle_set_hash = cs.cycle_set_hash
      )
    RETURNING id
  )
  SELECT count(*) INTO v_cancellation_count FROM inserted;

  SELECT
    count(*) FILTER (WHERE family_state = 'resolved'),
    count(*) FILTER (WHERE family_state = 'unresolved')
  INTO v_family_resolved, v_family_unresolved
  FROM public.makesafe_state_identity_current_v2
  WHERE job_id = ANY(p_job_ids);

  v_result := jsonb_build_object(
    'ok', true,
    'run_key', p_run_key,
    'selection_hash', p_selection_hash,
    'requested', v_requested,
    'identity_revisions_inserted', v_identity_count,
    'attendance_cycles_created', v_cycle_count,
    'facts_seeded_or_bound', v_fact_count,
    'family_resolved', v_family_resolved,
    'family_unresolved', v_family_unresolved,
    'terminal_proofs_inserted', v_terminal_count,
    'cancellations_inserted', v_cancellation_count,
    'idempotent_replay', false
  );

  INSERT INTO public.makesafe_state_seed_runs (
    run_key,
    selection_hash,
    requested_count,
    result_json,
    applied_by
  ) VALUES (
    p_run_key,
    p_selection_hash,
    v_requested,
    v_result,
    p_applied_by
  );

  RETURN v_result;
END;
$$;

CREATE TABLE IF NOT EXISTS public.makesafe_board_attention_marks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key text NOT NULL CHECK (length(btrim(run_key)) BETWEEN 1 AND 160),
  job_id uuid NOT NULL REFERENCES public.jobs(id) ON DELETE RESTRICT,
  job_number text NOT NULL CHECK (length(btrim(job_number)) > 0),
  attendance_cycle_id uuid
    REFERENCES public.makesafe_attendance_cycles(id) ON DELETE RESTRICT,
  state text NOT NULL CHECK (state IN ('active', 'resolved')),
  code text NOT NULL CHECK (length(btrim(code)) > 0),
  message text NOT NULL CHECK (length(btrim(message)) > 0),
  evidence_refs jsonb NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(evidence_refs) = 'array'),
  computed_at timestamptz NOT NULL,
  marked_by text NOT NULL CHECK (length(btrim(marked_by)) > 0),
  marked_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT makesafe_board_attention_marks_idempotency
    UNIQUE (run_key, job_id)
);

CREATE INDEX IF NOT EXISTS idx_makesafe_board_attention_marks_current
  ON public.makesafe_board_attention_marks (job_id, marked_at DESC, id DESC);

COMMENT ON TABLE public.makesafe_board_attention_marks IS
  'Append-only display markers for make-safe cards whose status cannot be corrected automatically. Active rows contain the exact plain-English Captain action; resolved rows clear an earlier mark.';

CREATE OR REPLACE FUNCTION public.guard_makesafe_board_attention_mark_insert()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_job_number text;
  v_job_type text;
BEGIN
  SELECT job_number, type
  INTO v_job_number, v_job_type
  FROM public.jobs
  WHERE id = NEW.job_id;

  IF NOT FOUND
     OR v_job_type <> 'makesafe'
     OR v_job_number IS DISTINCT FROM NEW.job_number THEN
    RAISE EXCEPTION 'attention mark job identity is not a current make-safe';
  END IF;
  IF NEW.attendance_cycle_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.makesafe_attendance_cycles c
    WHERE c.id = NEW.attendance_cycle_id
      AND c.job_id = NEW.job_id
  ) THEN
    RAISE EXCEPTION 'attention mark attendance cycle belongs to another job';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.reject_makesafe_board_attention_mark_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  RAISE EXCEPTION 'makesafe_board_attention_marks is append-only';
END;
$$;

DROP TRIGGER IF EXISTS trg_makesafe_board_attention_marks_insert_guard
  ON public.makesafe_board_attention_marks;
CREATE TRIGGER trg_makesafe_board_attention_marks_insert_guard
  BEFORE INSERT ON public.makesafe_board_attention_marks
  FOR EACH ROW
  EXECUTE FUNCTION public.guard_makesafe_board_attention_mark_insert();

DROP TRIGGER IF EXISTS trg_makesafe_board_attention_marks_append_only
  ON public.makesafe_board_attention_marks;
CREATE TRIGGER trg_makesafe_board_attention_marks_append_only
  BEFORE UPDATE OR DELETE ON public.makesafe_board_attention_marks
  FOR EACH ROW
  EXECUTE FUNCTION public.reject_makesafe_board_attention_mark_mutation();

CREATE OR REPLACE VIEW public.makesafe_board_attention_current
WITH (security_invoker = true)
AS
SELECT
  id,
  run_key,
  job_id,
  job_number,
  attendance_cycle_id,
  state,
  code,
  message,
  evidence_refs,
  computed_at,
  marked_by,
  marked_at
FROM (
  SELECT DISTINCT ON (job_id) *
  FROM public.makesafe_board_attention_marks
  ORDER BY job_id, marked_at DESC, id DESC
) latest
WHERE state = 'active';

COMMENT ON VIEW public.makesafe_board_attention_current IS
  'Latest unresolved plain-English Captain action for each make-safe card.';

CREATE TABLE IF NOT EXISTS public.makesafe_board_reconciliation_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key text NOT NULL UNIQUE
    CHECK (length(btrim(run_key)) BETWEEN 1 AND 160),
  selection_hash text NOT NULL
    CHECK (selection_hash ~ '^sha256:[0-9a-f]{64}$'),
  requested_count integer NOT NULL CHECK (requested_count > 0),
  trustworthy_count integer NOT NULL CHECK (trustworthy_count >= 0),
  captain_marked_count integer NOT NULL CHECK (captain_marked_count >= 0),
  neither_count integer NOT NULL CHECK (neither_count = 0),
  transition_count integer NOT NULL CHECK (transition_count >= 0),
  result_json jsonb NOT NULL CHECK (jsonb_typeof(result_json) = 'object'),
  applied_by text NOT NULL CHECK (length(btrim(applied_by)) > 0),
  applied_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT makesafe_board_reconciliation_partition_check CHECK (
    trustworthy_count + captain_marked_count = requested_count
  )
);

COMMENT ON TABLE public.makesafe_board_reconciliation_runs IS
  'Committed full-selection audit for fact-derived display corrections and Captain markers. Chunks are staged separately and become visible only at finalization.';

CREATE TABLE IF NOT EXISTS public.makesafe_board_reconciliation_staged_chunks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key text NOT NULL,
  selection_hash text NOT NULL
    CHECK (selection_hash ~ '^sha256:[0-9a-f]{64}$'),
  state_token_hash text NOT NULL
    CHECK (state_token_hash ~ '^sha256:[0-9a-f]{64}$'),
  chunk_index integer NOT NULL CHECK (chunk_index > 0),
  chunk_count integer NOT NULL CHECK (chunk_count > 0),
  rows_json jsonb NOT NULL CHECK (jsonb_typeof(rows_json) = 'array'),
  requested_count integer NOT NULL CHECK (requested_count BETWEEN 1 AND 500),
  staged_by text NOT NULL CHECK (length(btrim(staged_by)) > 0),
  staged_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (run_key, chunk_index)
);

COMMENT ON TABLE public.makesafe_board_reconciliation_staged_chunks IS
  'Invisible, idempotent reconciliation chunks. Only finalize_makesafe_board_reconciliation may publish them.';

CREATE OR REPLACE FUNCTION public.stage_makesafe_board_reconciliation(
  p_run_key text,
  p_applied_by text,
  p_selection_hash text,
  p_state_token_hash text,
  p_chunk_index integer,
  p_chunk_count integer,
  p_rows jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_requested integer;
  v_existing public.makesafe_board_reconciliation_staged_chunks%ROWTYPE;
BEGIN
  DELETE FROM public.makesafe_board_reconciliation_staged_chunks
  WHERE staged_at < now() - interval '24 hours';
  IF length(btrim(COALESCE(p_run_key, ''))) = 0
     OR length(btrim(COALESCE(p_applied_by, ''))) = 0
     OR COALESCE(p_selection_hash, '') !~ '^sha256:[0-9a-f]{64}$'
     OR COALESCE(p_state_token_hash, '') !~ '^sha256:[0-9a-f]{64}$'
     OR p_chunk_index < 1 OR p_chunk_count < p_chunk_index THEN
    RAISE EXCEPTION 'invalid reconciliation staging metadata';
  END IF;
  IF jsonb_typeof(p_rows) <> 'array' THEN
    RAISE EXCEPTION 'p_rows must be a JSON array';
  END IF;
  v_requested := jsonb_array_length(p_rows);
  IF v_requested < 1 OR v_requested > 500 THEN
    RAISE EXCEPTION 'p_rows must contain between 1 and 500 cards';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_rows) row_json
    WHERE jsonb_typeof(row_json->'state_token') <> 'string'
       OR COALESCE(row_json->>'state_token', '') !~ '^sha256:[0-9a-f]{64}$'
  ) THEN
    RAISE EXCEPTION 'every staged row requires a v2 state token';
  END IF;
  SELECT * INTO v_existing
  FROM public.makesafe_board_reconciliation_staged_chunks
  WHERE run_key = p_run_key AND chunk_index = p_chunk_index;
  IF FOUND THEN
    IF v_existing.selection_hash IS DISTINCT FROM p_selection_hash
       OR v_existing.state_token_hash IS DISTINCT FROM p_state_token_hash
       OR v_existing.chunk_count IS DISTINCT FROM p_chunk_count
       OR v_existing.rows_json IS DISTINCT FROM p_rows THEN
      RAISE EXCEPTION 'staged chunk retry does not match the original payload';
    END IF;
    RETURN jsonb_build_object(
      'ok', true, 'run_key', p_run_key, 'chunk_index', p_chunk_index,
      'requested', v_existing.requested_count, 'idempotent_replay', true
    );
  END IF;
  INSERT INTO public.makesafe_board_reconciliation_staged_chunks (
    run_key, selection_hash, state_token_hash, chunk_index, chunk_count,
    rows_json, requested_count, staged_by
  ) VALUES (
    p_run_key, p_selection_hash, p_state_token_hash, p_chunk_index,
    p_chunk_count, p_rows, v_requested, p_applied_by
  );
  RETURN jsonb_build_object(
    'ok', true, 'run_key', p_run_key, 'chunk_index', p_chunk_index,
    'requested', v_requested, 'idempotent_replay', false
  );
END;
$$;

